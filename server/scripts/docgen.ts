// Generates the documentation that must not drift from the code:
//   docs/CONFIGURATION.md        from the zod env schema (defaults) + src/config.docs.ts
//   docs/openapi.json            from the route declaration (src/routes/spec.ts) and the zod request schemas
//   docs/RATE-LIMITING.md table  from the policy registry (between the policies:start/end markers)
// Usage: tsx scripts/docgen.ts [config|api|all]. test/docs.test.ts fails when the committed files differ from a fresh generation.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { ENV_DOCS } from '../src/config.docs.js';
import { EnvSchema } from '../src/config.js';
import { buildPolicies } from '../src/ratelimit/policies.js';
import { ALL_PERMISSIONS, PERMISSIONS, SYSTEM_ROLES } from '../src/auth/permissions.js';
import { OPERATIONS } from '../src/routes/spec.js';

const docs = (f: string) => fileURLToPath(new URL(`../../docs/${f}`, import.meta.url));
const NO_ENV = { NODE_ENV: 'development' } as Record<string, string>;

function defaultsOf(): Record<string, unknown> {
  const parsed = EnvSchema.safeParse(NO_ENV);
  if (!parsed.success) throw new Error('config schema does not parse an empty environment');
  return parsed.data as Record<string, unknown>;
}

const show = (v: unknown): string => (v === undefined ? '' : Array.isArray(v) ? (v.length ? v.join(',') : '(empty)') : v === '' ? '(empty)' : `\`${String(v)}\``);
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function configDoc(): string {
  const defaults = defaultsOf();
  const rows = Object.keys(EnvSchema.shape).map((k) => {
    const d = ENV_DOCS[k as keyof typeof ENV_DOCS];
    const def = k === 'WEB_DIST' ? '`../web/dist`' : k === 'JWT_SECRET' ? '(generated in development)' : show(defaults[k]) || '(unset)';
    const req = d.required === 'production' ? 'in production' : d.required ? 'yes' : 'no';
    return `| \`${k}\` | ${cell(def)} | ${req} | ${d.example ? cell(`\`${d.example}\``) : ''} | ${cell(d.desc)}${d.security ? ` **Security:** ${cell(d.security)}` : ''} |`;
  });
  return `# Configuration

Generated from the zod schema in \`server/src/config.ts\` and the descriptions in \`server/src/config.docs.ts\` by \`npm run docs:config\`; \`npm test\` fails when this file is stale. Configuration is environment-only and validated at boot (the process refuses to start with an invalid value). Nothing is required in development. Copy \`.env.example\` for a starting point.

| Variable | Default | Required | Example | What it does |
|---|---|---|---|---|
${rows.join('\n')}

Booleans accept \`1/true/yes/on\` (case-insensitive); lists are comma-separated. Rate limit variables are explained in [RATE-LIMITING.md](RATE-LIMITING.md); database selection in [ARCHITECTURE.md](ARCHITECTURE.md#data-layer).
`;
}

export function policiesTable(): string {
  const cfg = defaultsOf() as Parameters<typeof buildPolicies>[0];
  const win = (ms: number) => (ms === 0 ? '' : ms % 3_600_000 === 0 ? `${ms / 3_600_000} h` : ms % 60_000 === 0 ? `${ms / 60_000} min` : `${ms / 1000} s`);
  const rows = buildPolicies(cfg).map((p) => {
    const tiers = p.tiers ? Object.entries(p.tiers).map(([k, v]) => `${k} x${v}`).join(', ') : '';
    const key = p.keyBy === 'composite' ? `composite(${(p.composite ?? []).join('+')})` : p.keyBy;
    const flags = [p.lease ? 'lease' : '', p.penalty ? 'penalty box' : '', p.idempotent ? 'idempotency key' : ''].filter(Boolean).join(', ');
    const limit = p.algo === 'concurrency' ? `${p.limit} in flight` : `${p.limit} / ${win(p.windowMs)}${p.algo === 'gcra' ? `, burst ${p.burst ?? p.limit}` : ''}`;
    return `| \`${p.id}\` | ${p.layer} | ${key} | ${p.algo} | ${limit}${p.cost !== 1 ? `, cost ${p.cost}` : ''} | ${p.onFail} | ${tiers} | ${flags} | ${cell(p.description)} |`;
  });
  return `Defaults, before environment overrides and plan multipliers (this table is generated by \`npm run docs:config\`).

| Policy | Layer | Key | Algorithm | Limit | On store failure | Tiers | Options | Purpose |
|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}`;
}

export function withPolicies(md: string): string {
  return md.replace(/<!-- policies:start -->[\s\S]*<!-- policies:end -->/, `<!-- policies:start -->\n${policiesTable()}\n<!-- policies:end -->`);
}

const schemaOf = (s: z.ZodType) => {
  const j = z.toJSONSchema(s, { unrepresentable: 'any', io: 'input', target: 'draft-2020-12' }) as Record<string, unknown>;
  delete j.$schema;
  return j;
};

export function openApi(): Record<string, unknown> {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const o of OPERATIONS) {
    const path = o.path.replace(/:([A-Za-z]+)/g, '{$1}').replace(/\/\*$/, '/{rest}');
    const params: unknown[] = [...[...path.matchAll(/\{([A-Za-z]+)\}/g)].map((m) => ({ name: m[1], in: 'path', required: true, schema: { type: 'string' } }))];
    if (o.query) {
      const q = schemaOf(o.query) as { properties?: Record<string, unknown>; required?: string[] };
      for (const [name, schema] of Object.entries(q.properties ?? {})) params.push({ name, in: 'query', required: q.required?.includes(name) ?? false, schema });
    }
    const secured = ['user', 'platform'].includes(o.auth);
    const gated = o.auth === 'platform' || (!!o.permission && o.permission !== 'any');
    const op: Record<string, unknown> = {
      tags: [o.tag],
      summary: o.summary,
      ...(o.notes ? { description: o.notes } : {}),
      operationId: `${o.method.toLowerCase()}_${path.replace(/[^A-Za-z0-9]+/g, '_').replace(/^_|_$/g, '')}`,
      parameters: params,
      ...(o.body ? { requestBody: { required: true, content: { 'application/json': { schema: schemaOf(o.body) } } } } : {}),
      responses: {
        [String(o.status ?? 200)]: { description: o.status === 204 ? 'No content' : 'Success' },
        '400': { $ref: '#/components/responses/Error' },
        ...(secured ? { '401': { $ref: '#/components/responses/Error' } } : {}),
        ...(gated ? { '403': { $ref: '#/components/responses/Error' } } : {}),
        ...(o.path.includes(':') ? { '404': { $ref: '#/components/responses/Error' } } : {}),
        ...(o.exempt ? {} : { '429': { $ref: '#/components/responses/RateLimited' } }),
      },
      ...(secured ? { security: [{ bearer: [] }] } : {}),
      'x-auth': o.auth,
      ...(o.permission ? { 'x-permission': o.permission } : {}),
      'x-rate-limit-policies': [...o.limits, ...(o.inHandler ?? [])],
      ...(o.cost && o.cost !== 1 ? { 'x-rate-limit-cost': o.cost } : {}),
      ...(o.exempt ? { 'x-rate-limit-exempt': o.exempt } : {}),
    };
    (paths[path] ??= {})[o.method.toLowerCase()] = op;
  }
  const retry = { description: 'Seconds to wait before retrying', schema: { type: 'integer' } };
  return {
    openapi: '3.1.0',
    info: { title: 'Funnels API', version: '1.0.0', description: 'Generated from server/src/routes/spec.ts by `npm run docs:api`. Errors are `{ error: { code, message, details? } }`; lists are `{ data, pagination }`. See docs/API.md for examples and docs/RATE-LIMITING.md for limits.' },
    servers: [{ url: 'http://localhost:3000' }],
    paths,
    components: {
      securitySchemes: { bearer: { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' } },
      schemas: { Error: { type: 'object', required: ['error'], properties: { error: { type: 'object', required: ['code', 'message'], properties: { code: { type: 'string' }, message: { type: 'string' }, details: {} } } } } },
      responses: {
        Error: { description: 'Error', content: { 'application/json': { schema: { $ref: '#/components/schemas/Error' } } } },
        RateLimited: {
          description: 'Rate limited (429) or overloaded (503). Always carries Retry-After and RateLimit headers.',
          headers: { 'Retry-After': retry, 'RateLimit-Policy': { schema: { type: 'string' } }, RateLimit: { schema: { type: 'string' } } },
          content: { 'application/json': { schema: { type: 'object', properties: { error: { type: 'object', properties: { code: { type: 'string', enum: ['RATE_LIMITED', 'OVERLOADED', 'RATE_LIMITER_UNAVAILABLE'] }, message: { type: 'string' }, retry_after_s: { type: 'integer' }, policy: { type: 'string' } } } } } } },
        },
      },
    },
  };
}

const roleCols = Object.values(SYSTEM_ROLES);

/** Every permission, what it allows, and which built-in roles have it (generated; the source is src/auth/permissions.ts). */
export function permissionsTable(): string {
  const rows = ALL_PERMISSIONS.map((p) => `| \`${p}\` | ${PERMISSIONS[p]} | ${roleCols.map((r) => (r.permissions.includes(p) ? 'yes' : '')).join(' | ')} |`);
  return `Generated by \`npm run docs:config\` from \`server/src/auth/permissions.ts\`.

| Permission | Allows | ${roleCols.map((r) => r.name).join(' | ')} |
|---|---|${roleCols.map(() => '---').join('|')}|
${rows.join('\n')}`;
}

/** Which permission each route needs (generated from the route declaration, so it cannot drift from what is enforced). */
export function routesTable(): string {
  const by = new Map<string, string[]>();
  for (const o of OPERATIONS) {
    if (o.auth !== 'user') continue;
    const k = o.permission === 'any' ? 'any signed-in member' : `\`${o.permission}\``;
    (by.get(k) ?? by.set(k, []).get(k)!).push(`\`${o.method} ${o.path}\``);
  }
  const ordered = [...by.entries()].sort(([a], [b]) => (a.startsWith('any') ? -1 : b.startsWith('any') ? 1 : a < b ? -1 : 1));
  return `Generated from \`server/src/routes/spec.ts\`.

| Permission | Routes |
|---|---|
${ordered.map(([k, v]) => `| ${k} | ${v.join('<br>')} |`).join('\n')}`;
}

export function withRbac(md: string): string {
  return md
    .replace(/<!-- permissions:start -->[\s\S]*<!-- permissions:end -->/, `<!-- permissions:start -->\n${permissionsTable()}\n<!-- permissions:end -->`)
    .replace(/<!-- routes:start -->[\s\S]*<!-- routes:end -->/, `<!-- routes:start -->\n${routesTable()}\n<!-- routes:end -->`);
}

export const openApiText = (): string => `${JSON.stringify(openApi(), null, 2)}\n`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const mode = process.argv[2] ?? 'all';
  if (mode === 'config' || mode === 'all') {
    writeFileSync(docs('CONFIGURATION.md'), configDoc());
    writeFileSync(docs('RATE-LIMITING.md'), withPolicies(readFileSync(docs('RATE-LIMITING.md'), 'utf8')));
    writeFileSync(docs('RBAC.md'), withRbac(readFileSync(docs('RBAC.md'), 'utf8')));
  }
  if (mode === 'api' || mode === 'all') writeFileSync(docs('openapi.json'), openApiText());
  process.stdout.write(`docs generated (${mode})\n`);
}
